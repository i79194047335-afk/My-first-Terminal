"""
Сетка выплат intrade.bar и окна пониженной выплаты. Python 3.10.

Зачем модуль, если процент можно просто спросить у площадки: спросить нужно
ВСЕГДА (ajax_percent.php перед каждой ставкой — единственный источник истины),
но знать сетку заранее тоже надо. Во-первых, чтобы поймать расхождение между
ожиданием и ответом — оно означает, что площадка поменяла правила. Во-вторых,
чтобы бэктест и планирование не ходили в сеть на каждую свечу.

Сетка со слов владельца (2026-08-05), подтверждена живыми запросами:

| Экспирация      | Ставка      | Выплата |
|-----------------|-------------|---------|
| 1 и 3 мин       | до 5000 р   | 82%     |
| 1 и 3 мин       | от 5000 р   | 85%     |
| 4…500 мин       | до 5000 р   | 79%     |
| 4…500 мин       | от 5000 р   | 85%     |

ОКНО У НАЧАЛА ЧАСА: за 3 минуты до и после начала часа выплата падает до 60%,
и действует это с 17:00 до 09:00 МСК следующего дня.

Почему окно важнее всей остальной сетки. Безубыточный винрейт равен
100/(100+p):

    выплата 85% → нужен WR 54.1%
    выплата 82% → нужен WR 54.9%
    выплата 79% → нужен WR 55.9%
    выплата 60% → нужен WR 62.5%   ← +7.6 п.п. к порогу

Стратегия с WR 58% прибыльна при 82% и убыточна при 60%. Шесть минут у
каждого часа в течение шестнадцати часов суток — это 96 минут, 10% всего
времени. Заходить туда вслепую значит методично отдавать деньги, поэтому
ограничитель обязан резать такие входы до отправки запроса.

Проверено живьём 2026-08-05 22:09 МСК: 1 мин/ставка 1 → 82%, 1 мин/ставка
100 → 85%, 3 мин → 82%. Порог «5000 рублей» на долларовом счёте отрабатывает
около 100 единиц. Classic (5 и 60 мин) ночью отдаёт 0% — площадка так
сообщает «сейчас не торгуется», и ноль надо трактовать как запрет, а не
как сбой разбора.
"""

from __future__ import annotations

from datetime import datetime, timedelta, timezone  # noqa: F401 — timezone нужен is_broker_down

# Часовой пояс Москвы. Площадка живёт по нему: и «крайнее время 18:00»,
# и ночные ограничения, и окно у начала часа заданы в МСК.
MSK = timezone(timedelta(hours=3))

# Порог крупной ставки: 80 долларов ВКЛЮЧИТЕЛЬНО.
#
# Найден перебором с точностью до цента (2026-08-05, USD/JPY, 1 мин):
#   79.99 → 82%,  80.00 → 85%
# То есть «5000 рублей» из описания площадки на долларовом счёте означают
# ровно 80 единиц, и граница именно >=, а не >.
#
# Значение всё равно остаётся ОЖИДАНИЕМ: истину говорит ajax_percent.php
# перед каждой ставкой. Расхождение — признак, что правила поменялись.
LARGE_STAKE = 80.0

# Выплата в окне у начала часа.
HOUR_EDGE_PERCENT = 60

# Полуширина окна в минутах: за 3 минуты до и 3 минуты после начала часа.
HOUR_EDGE_MINUTES = 3

# Окно пониженной выплаты действует с 17:00 до 09:00 МСК следующего дня.
HOUR_EDGE_FROM_HOUR = 17
HOUR_EDGE_TO_HOUR = 9

# ОКНО ПРОСТОЯ БРОКЕРА: 21:00–23:00 UTC ежедневно (со слов владельца,
# 2026-08-06). Торговли в это время нет вовсе — это не «низкая выплата»,
# а закрытая площадка. Задано в UTC, а не в МСК: у брокера сутки считаются
# по UTC, и пересчёт через московское время добавил бы лишний повод для
# ошибки на переводе часов.
#
# Практическое следствие для замера задержки (Слой 7): выборка не должна
# упираться в эту границу. Прогон, начатый в 20:50 UTC, оборвётся на
# половине, и часть сделок вернёт ошибку вместо результата.
BROKER_DOWN_FROM_UTC = 21
BROKER_DOWN_TO_UTC = 23


def breakeven_winrate(percent: float) -> float:
    """Винрейт, при котором ставки выходят в ноль.

    Бинарный опцион: выигрыш даёт +percent% от ставки, проигрыш забирает
    100%. Ноль достигается при WR = 100/(100+percent).

    Args:
        percent: Процент выплаты (82 означает 82%).

    Returns:
        Безубыточный винрейт в процентах. Для нулевой выплаты — 100.0,
        то есть «выиграть невозможно».
    """
    if percent <= 0:
        return 100.0
    return 100.0 / (100.0 + percent) * 100.0


def expected_percent(expiry_minutes: int, investment: float) -> int:
    """Какую выплату ожидаем по сетке, без обращения к площадке.

    Значение ОЖИДАЕМОЕ. Перед реальной ставкой всё равно вызывается
    ajax_percent.php: сетка может измениться без предупреждения, и
    расхождение с ней — сигнал, что правила поменялись.

    Args:
        expiry_minutes: Экспирация в минутах.
        investment:     Размер ставки в валюте счёта.

    Returns:
        Ожидаемый процент выплаты.
    """
    large = investment >= LARGE_STAKE
    if expiry_minutes <= 3:
        return 85 if large else 82
    return 85 if large else 79


def is_hour_edge(moment: datetime = None) -> bool:
    """Попадает ли момент в окно пониженной выплаты у начала часа.

    Окно: ±3 минуты от начала часа, действует с 17:00 до 09:00 МСК
    следующего дня. Проверяется по времени ПЛОЩАДКИ (МСК), а не по UTC и
    не по локальным часам сервера.

    Args:
        moment: Момент времени (aware datetime). По умолчанию — сейчас.

    Returns:
        True, если в этот момент выплата урезана до 60%.
    """
    if moment is None:
        moment = datetime.now(MSK)
    msk = moment.astimezone(MSK)

    # Ночной интервал пересекает полночь, поэтому условие через «или».
    in_night = msk.hour >= HOUR_EDGE_FROM_HOUR or msk.hour < HOUR_EDGE_TO_HOUR
    if not in_night:
        return False

    # Близость к началу часа: первые 3 минуты часа либо последние 3.
    near_start = msk.minute < HOUR_EDGE_MINUTES
    near_end = msk.minute >= 60 - HOUR_EDGE_MINUTES
    return near_start or near_end


def minutes_until_hour_edge(moment: datetime = None) -> float:
    """Сколько минут осталось до ближайшего окна пониженной выплаты.

    Нужно исполнителю, чтобы не открывать минутную сделку, которая
    ЗАКРОЕТСЯ уже внутри окна: выплата фиксируется на входе, но проверять
    стоит обе границы, пока поведение площадки на стыке не изучено.

    Args:
        moment: Момент времени (aware datetime). По умолчанию — сейчас.

    Returns:
        Минуты до начала окна; 0.0, если окно уже идёт.
    """
    if moment is None:
        moment = datetime.now(MSK)
    msk = moment.astimezone(MSK)

    if is_hour_edge(msk):
        return 0.0

    # Окно начинается за HOUR_EDGE_MINUTES до начала следующего часа.
    minutes_to_hour = 60 - msk.minute - msk.second / 60.0
    return max(0.0, minutes_to_hour - HOUR_EDGE_MINUTES)


def is_broker_down(moment: datetime = None) -> bool:
    """Идёт ли ежедневное окно простоя брокера (21:00–23:00 UTC).

    В это время площадка не торгует вовсе. Отличается от окна пониженной
    выплаты принципиально: там сделку взять можно, но невыгодно, здесь —
    нельзя вообще.

    Args:
        moment: Момент времени (aware datetime). По умолчанию — сейчас.

    Returns:
        True, если торговля сейчас недоступна.
    """
    if moment is None:
        moment = datetime.now(timezone.utc)
    utc = moment.astimezone(timezone.utc)
    return BROKER_DOWN_FROM_UTC <= utc.hour < BROKER_DOWN_TO_UTC


def minutes_until_broker_down(moment: datetime = None) -> float:
    """Сколько минут осталось до окна простоя брокера.

    Нужно перед долгим прогоном: серию из 20+ сделок нет смысла начинать
    за полчаса до закрытия площадки — она оборвётся на середине.

    Args:
        moment: Момент времени (aware datetime). По умолчанию — сейчас.

    Returns:
        Минуты до начала окна; 0.0, если окно уже идёт.
    """
    if moment is None:
        moment = datetime.now(timezone.utc)
    utc = moment.astimezone(timezone.utc)

    if is_broker_down(utc):
        return 0.0

    hours_left = (BROKER_DOWN_FROM_UTC - utc.hour) % 24
    return hours_left * 60 - utc.minute - utc.second / 60.0


def describe(percent: float, moment: datetime = None) -> str:
    """Человеческое описание выплаты для панели и логов.

    Args:
        percent: Процент выплаты, полученный от площадки.
        moment:  Момент времени. По умолчанию — сейчас.

    Returns:
        Строка вида "82% (безубыток 54.9%)" с пометкой об окне, если оно идёт.
    """
    text = f"{percent:.0f}% (безубыток {breakeven_winrate(percent):.1f}%)"
    if is_hour_edge(moment):
        text += " ⚠ окно у начала часа"
    return text
